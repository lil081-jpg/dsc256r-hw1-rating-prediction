def featureQ5(datum):
    # Implement
    return [1, len(datum['review/text'])]

def Q5(dataset, feat_func):
    # Implement

    X = [feat_func(d) for d in dataset]
    y = [d['review/overall'] >= 4 for d in dataset]

    model = linear_model.LogisticRegression(class_weight='balanced')
    model.fit(X, y)

    predictions = model.predict(X)

    TP = sum((p == True) and (a == True) for p, a in zip(predictions, y))
    TN = sum((p == False) and (a == False) for p, a in zip(predictions, y))
    FP = sum((p == True) and (a == False) for p, a in zip(predictions, y))
    FN = sum((p == False) and (a == True) for p, a in zip(predictions, y))

    TPR = TP / (TP + FN)
    TNR = TN / (TN + FP)

    BER = 1 - 0.5 * (TPR + TNR)

    return TP, TN, FP, FN, BER

