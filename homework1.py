### Question 1

def getMaxLen(dataset):
    # Find the longest review (number of characters)
    maxLen = max(len(d['review_text']) for d in dataset)
    return maxLen

def featureQ1(datum, maxLen):
    # Feature vector for one data point
    return [1, len(datum['review_text']) / maxLen]

def Q1(dataset):
    # Implement...
    maxLen = getMaxLen(dataset)

    X = [featureQ1(d, maxLen) for d in dataset]
    y = [d['rating'] for d in dataset]

    model = linear_model.LinearRegression(fit_intercept=False)
    model.fit(X, y)

    theta = model.coef_
    predictions = model.predict(X)

    MSE = numpy.mean((numpy.array(y) - predictions)**2)

    return theta, MSE

